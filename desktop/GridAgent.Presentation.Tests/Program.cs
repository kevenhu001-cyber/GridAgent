using System.Text.Json;
using GridAgent.Windows;

static void Check(bool condition, string description)
{
    if (!condition) throw new InvalidOperationException(description);
}
var state = new ConversationState();
state.Append("You", "Question");
state.Delta("partial");
state.Delta(" text");
Check(state.Messages.Count == 2 && state.Messages[1].StreamText == "partial text", "Stream aggregates");
state.Complete("authoritative answer");
Check(state.Messages.Count == 2 && state.Messages[1].Body == "authoritative answer", "Final replaces preview");
state.Delta("another");
state.Interrupt();
Check(state.Messages[^1].Role == "Interrupted response", "Interrupted response is labelled");
state.Delta("temporary");
state.Complete("");
Check(state.Messages.Count == 3, "Empty final removes preview");
state.Activity("one");
state.Activity("two");
Check(state.Messages[^1].ActivityCount == 2, "Tool group aggregates");
var activity = state.Messages[^1];
Check(!activity.ActivityExpanded, "Activity is collapsed by default");
activity.SetActivityExpanded(true);
state.Activity("latest action");
Check(activity.ActivityExpanded && activity.Latest == "latest action", "User expansion persists during updates");
activity.SetActivityExpanded(false);
Check(!activity.ActivityExpanded, "Activity can be collapsed again");
var id = new string('a', 32);
var artifact = new RunArtifact(id, "andes", "fault", "ok", "kundur", null, [], ["waveform"]);
state.Artifact(artifact, _ => { }, _ => { });
state.Artifact(artifact, _ => { }, _ => { });
Check(state.Messages.Count == 5, "Run identity deduplicates cards");
state.Preview(new RunPreview(id, "B1", "s", "pu", false, 2, [0, 1], [1, 0.9]));
Check(state.Messages[^1].Preview?.SourcePoints == 2, "Preview updates same card");
state.Research(new ResearchSnapshot(id, "running", "", 1, 3), _ => { });
state.Research(new ResearchSnapshot(id, "passed", "", 2, 3), _ => { });
Check(state.Messages.Count == 6 && state.Messages[^1].Research?.Stage == "passed", "Research updates same card");
state.Clear();
Check(state.Messages.Count == 0 && !state.HasArtifact(id), "Clear resets identity index");
using var unknown = JsonDocument.Parse("""{"schema":"future","kind":"run","id":"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"}""");
Check(RunArtifact.Parse(unknown.RootElement) == null, "Unknown schema ignored");
using var malformed = JsonDocument.Parse("""{"schema":1,"kind":"run","id":"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"}""");
Check(RunArtifact.Parse(malformed.RootElement) == null, "Malformed schema ignored");
using var valid = JsonDocument.Parse("""{"schema":"gridagent.artifact.v1","kind":"run","id":"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa","backend":"andes","operation":"fault","status":"ok","case":"kundur","quality":{"passed":2,"total":3,"protocol":"check"},"metrics":[{"name":"v","value":0.9}],"views":["waveform","invalid"]}""");
var parsed = RunArtifact.Parse(valid.RootElement);
Check(parsed is { HasPreview: true, Quality.Passed: 2 } && parsed.Views.Length == 1, "Typed projection validated");
Console.WriteLine("Presentation contract and conversation state checks passed.");
